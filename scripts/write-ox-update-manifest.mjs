/**
 * Write public/ox-update-manifest.json and sync Android versionName/versionCode
 * from apps/os-experience/ox-versions.json (single source of truth).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash, randomUUID } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appDir = join(root, "apps", "os-experience");
const versionsPath = join(appDir, "ox-versions.json");
const publicDir = join(appDir, "public");
const manifestPath = join(publicDir, "ox-update-manifest.json");
const gradlePath = join(appDir, "android", "app", "build.gradle");

const versions = JSON.parse(readFileSync(versionsPath, "utf8"));
const publishedAt = new Date().toISOString();
const releaseId =
  process.env.OX_RELEASE_ID?.trim() ||
  `ox-${publishedAt.slice(0, 10).replace(/-/g, "")}-${createHash("sha1")
    .update(`${versions.nativeVersion}:${versions.nativeBuildNumber}:${versions.runtimeVersion}:${publishedAt}`)
    .digest("hex")
    .slice(0, 10)}`;

const runtimeUrl = (
  process.env.OX_LIVE_URL ||
  versions.runtimeUrl ||
  process.env.CAPACITOR_SERVER_URL ||
  "https://xperience.getlifeos.app"
).replace(/\/$/, "");

const apkUrl =
  (process.env.OX_APK_URL || versions.apkUrl || "").trim() ||
  `${runtimeUrl}/releases/OS-Xperience.apk`;

const manifest = {
  nativeVersion: String(versions.nativeVersion),
  nativeBuildNumber: Number(versions.nativeBuildNumber),
  runtimeVersion: String(versions.runtimeVersion),
  minimumRuntimeVersion: String(versions.minimumRuntimeVersion),
  minimumNativeVersion: String(versions.minimumNativeVersion),
  minimumNativeBuildNumber: Number(versions.minimumNativeBuildNumber),
  releaseId,
  publishedAt,
  apkUrl,
  runtimeUrl,
  notes: versions.notes || undefined,
};

if (!existsSync(publicDir)) mkdirSync(publicDir, { recursive: true });
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
console.log(`Wrote ${manifestPath}`);
console.log(`  native ${manifest.nativeVersion} (${manifest.nativeBuildNumber})`);
console.log(`  runtime ${manifest.runtimeVersion}`);
console.log(`  releaseId ${manifest.releaseId}`);

if (existsSync(gradlePath)) {
  let gradle = readFileSync(gradlePath, "utf8");
  gradle = gradle.replace(/versionCode\s+\d+/, `versionCode ${manifest.nativeBuildNumber}`);
  gradle = gradle.replace(/versionName\s+"[^"]+"/, `versionName "${manifest.nativeVersion}"`);
  writeFileSync(gradlePath, gradle, "utf8");
  console.log(`Synced Android build.gradle → ${manifest.nativeVersion} / ${manifest.nativeBuildNumber}`);
}

// Stamp a tiny module the web runtime can import without fetch (bundled identity).
const stampPath = join(appDir, "src", "ox-version-stamp.ts");
writeFileSync(
  stampPath,
  `/** Auto-generated by scripts/write-ox-update-manifest.mjs — do not edit. */\n` +
    `export const OX_NATIVE_VERSION = ${JSON.stringify(manifest.nativeVersion)};\n` +
    `export const OX_NATIVE_BUILD_NUMBER = ${manifest.nativeBuildNumber};\n` +
    `export const OX_RUNTIME_VERSION = ${JSON.stringify(manifest.runtimeVersion)};\n` +
    `export const OX_RELEASE_ID = ${JSON.stringify(manifest.releaseId)};\n` +
    `export const OX_RUNTIME_URL = ${JSON.stringify(manifest.runtimeUrl)};\n`,
  "utf8",
);
console.log(`Wrote ${stampPath}`);

void randomUUID;
